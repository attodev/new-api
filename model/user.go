func (user *User) Update(updatePassword bool) error {
	var err error
	if updatePassword {
		user.Password, err = common.Password2Hash(user.Password)
		if err != nil {
			return err
		}
	}
	newUser := *user
	err = DB.Transaction(func(tx *gorm.DB) error {
		var current User
		if err := tx.Clauses(clause.Locking{Strength: "UPDATE"}).First(&current, user.Id).Error; err != nil {
			return err
		}
		if newUser.Status == common.UserStatusDisabled {
			if err := DeactivateTossBillingForUser(tx, user.Id); err != nil {
				return err
			}
		}
		// Omit fields that other code paths update out-of-band (billing,
		// affiliate accrual, access-token rotation) - a routine profile edit
		// built from a snapshot taken before one of those ran must not write
		// its now-stale value back over the concurrent change.
		return tx.Model(&current).Omit(
			"access_token",
			"quota",
			"used_quota",
			"request_count",
			"aff_count",
			"aff_quota",
			"aff_history",
		).Updates(newUser).Error
	})
	if err != nil {
		return err
	}
	if err := DB.First(user, user.Id).Error; err != nil {
		return err
	}

	// Update cache
	return updateUserCache(*user)
}

// UpdateUserFieldsWithBillingLifecycle applies controller-owned field updates
// while ensuring a transition to disabled atomically stops recurring billing.
func UpdateUserFieldsWithBillingLifecycle(id int, updates map[string]interface{}) error {
	if id <= 0 {
		return errors.New("id is empty")
	}
	return DB.Transaction(func(tx *gorm.DB) error {
		var current User
		if err := tx.Clauses(clause.Locking{Strength: "UPDATE"}).First(&current, id).Error; err != nil {
			return err
		}
		if status, ok := updates["status"].(int); ok && status == common.UserStatusDisabled {
			if err := DeactivateTossBillingForUser(tx, id); err != nil {
				return err
			}
		}
		return tx.Model(&current).Updates(updates).Error
	})
}

